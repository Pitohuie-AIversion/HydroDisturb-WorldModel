@dataclass(frozen=True)
class TrajectorySegmentRecord:
    segment_id: str
    num_frames: int
    dt_phys_s: float
    t_start_s: float
    t_end_s: float
    file_names: tuple[str, ...]


def detect_temporal_rank_degeneracy(field_t4zyx: np.ndarray, rank_threshold: int = 2, rtol: float = 1e-4) -> tuple[bool, int]:
    """Detect synthetic rank-2 linear-interpolation trajectories (such as `c04_wm_25steps_golden.h5`).

    If a T-step sequence (T >= 5) was generated by linearly interpolating 2 endpoint frames,
    all time-difference vectors lie in a 1D (or <=2D) subspace, so its singular value spectrum
    has effective numerical rank <= 2.
    """
    f = np.asarray(field_t4zyx, dtype=np.float64)
    if f.ndim != 5 or f.shape[0] < 5:
        return False, int(f.shape[0])
    # Subsample spatial grid for fast SVD rank check
    sub = f[:, :, ::4, ::4, ::4]
    sub = np.where(np.isfinite(sub), sub, 0.0)
    diffs = np.diff(sub.reshape(f.shape[0], -1), axis=0)
    s = np.linalg.svd(diffs, full_matrices=False, compute_uv=False)
    if s.size == 0 or s[0] <= 1e-12:
        return True, 0
    eff_rank = int(np.sum(s > s[0] * rtol))
    return eff_rank <= rank_threshold, eff_rank


def load_c04_benchmark_npz(
    npz_path: str | Path,
    case_id: str = "C04",
    ancestor_id: str = "c04_re126k_anchor",
    trajectory_id: str = "c04_s1_volume_sequence",
    normalize: bool = True,
) -> tuple[Flow3DBatch, dict[str, Any]]:
    """Explicit adapter for `HydroDisturb-Bench/runs/c04_s1_volume_sequence.npz`."""
    p = Path(npz_path)
    if not p.exists():
        raise FileNotFoundError(f"C04 benchmark NPZ not found: {p}")
    with np.load(p, allow_pickle=False) as d:
        keys = set(d.files)
        required = {"fields", "times", "solid_mask", "sdf"}
        if not required.issubset(keys):
            raise PhysicsContractError(
                f"unrecognized C04 benchmark NPZ format at {p}; required keys {sorted(required)}, got {sorted(keys)}"
            )
        fields = np.asarray(d["fields"], dtype=np.float32)  # (T, 4, 64, 96, 192)
        times = np.asarray(d["times"], dtype=np.float64)
        solid_mask = np.asarray(d["solid_mask"])
        sdf_m = np.asarray(d["sdf"], dtype=np.float32)
        meta = json.loads(str(d["metadata_json"])) if "metadata_json" in keys else {}

    if fields.ndim != 5 or fields.shape[1] != 4:
        raise PhysicsContractError(f"expected fields (T, 4, Z, Y, X), got {fields.shape}")
    if times.ndim != 1 or times.shape[0] != fields.shape[0]:
        raise PhysicsContractError("times length must match fields T dimension")
    if times.shape[0] > 1 and np.any(np.diff(times) <= 0):
        raise PhysicsContractError("times in C04 volume sequence must be strictly increasing")

    diameter_m = float(meta.get("cylinder_diameter_m", 0.3))
    spacing_m = float(meta.get("cell_spacing_m", 0.01875))
    # Flip polarity: solid_mask (True=solid) -> fluid_mask (1.0=fluid, 0.0=solid)
    fluid_mask = (1.0 - (solid_mask > 0.5).astype(np.float32))
    # Dimensionless SDF/D
    sdf_over_d = (sdf_m / diameter_m).astype(np.float32)
    geometry = np.stack([fluid_mask, sdf_over_d], axis=0)[None, ...]  # (1, 2, Z, Y, X)

    if normalize:
        normalizer = Flow3DNormalizer()
        _, b_stats = normalizer.normalize(fields[None, ...], fluid_mask)
    else:
        b_stats = None
    dt_s = float(np.mean(np.diff(times))) if times.size > 1 else 0.06
    u0_m_s = 0.5
    cond = Flow3DConditions(
        reynolds_number=126167.05,
        u0_m_s=u0_m_s,
        diameter_m=diameter_m,
        viscosity_m2_s=1.1889e-6,
        dt_phys_s=dt_s,
        text_prompt="3D cylinder wake Re=126167 C04 baseline",
        known_mask={"reynolds_number": True, "u0_m_s": True, "diameter_m": True, "dt_phys_s": True},
        valid_mask={"reynolds_number": True, "u0_m_s": True, "diameter_m": True, "dt_phys_s": True},
    )
    provs = [
        SampleProvenance(
            case_id=case_id,
            geometry_id="cylinder_3d_D0p3m",
            trajectory_id=trajectory_id,
            ancestor_id=ancestor_id,
            segment_id="seg_0_dt0p06",
            time_idx=int(i),
            time_phys_s=float(t),
            time_ctu=float(t * u0_m_s / diameter_m),
            ground_truth_verified=True,
            tier1_stability_status="BENCHMARK_REFERENCE_4FRAME",
        )
        for i, t in enumerate(times)
    ]
    batch = Flow3DBatch(
        field=fields[None, ...],
        geometry=geometry,
        b=b_stats if normalize else None,
        spacing=(spacing_m, spacing_m, spacing_m),
        conditions=(cond,),
        provenance=tuple(provs),
    )
    summary = {
        "format": "c04_benchmark_npz",
        "path": str(p),
        "num_frames": int(fields.shape[0]),
        "spatial_shape_zyx": list(fields.shape[2:]),
        "dt_phys_s": dt_s,
        "dt_ctu": cond.resolved_dt_ctu,
        "solid_cells": int((fluid_mask <= 0.5).sum()),
        "fluid_cells": int((fluid_mask > 0.5).sum()),
        "sdf_over_d_min": float(sdf_over_d.min()),
        "sdf_over_d_max": float(sdf_over_d.max()),
        "supports_stage2_L4_window": bool(fields.shape[0] >= 5),
    }
    return batch, summary


def inspect_and_segment_c04_shedding_directory(
    dir_path: str | Path,
    reference_geometry_npz: str | Path | None = None,
    max_frames_to_load: int = 8,
) -> dict[str, Any]:
    """Inspect and segment `video_c04_shedding/*.npz` (82 files, YZX (96,64,192), solid NaNs, non-uniform dt)."""
    dpath = Path(dir_path)
    if not dpath.exists():
        raise FileNotFoundError(f"shedding directory not found: {dpath}")
    files = sorted(glob.glob(str(dpath / "*.npz")))
    if not files:
        raise PhysicsContractError(f"no .npz files found in {dpath}")

    meta_rows: list[tuple[float, int, str]] = []
    for fpath in files:
        with np.load(fpath, allow_pickle=False) as d:
            req = {"u", "v_span", "w_cross", "p", "time_s", "step"}
            if not req.issubset(set(d.files)):
                raise PhysicsContractError(f"unexpected keys in {fpath}: {d.files}")
            meta_rows.append((float(d["time_s"]), int(d["step"]), fpath))

    # Sort by physical time and step
    meta_rows.sort(key=lambda r: (r[0], r[1]))

    # Identify duplicate timestamps and partition into constant-dt segments
    dedup_rows: list[tuple[float, int, str]] = []
    duplicate_timestamps: list[dict[str, Any]] = []
    for row in meta_rows:
        if dedup_rows and abs(row[0] - dedup_rows[-1][0]) < 1e-7:
            duplicate_timestamps.append({
                "time_s": row[0],
                "kept_file": os.path.basename(dedup_rows[-1][2]),
                "dropped_duplicate_file": os.path.basename(row[2]),
            })
        else:
            dedup_rows.append(row)

    segments: list[TrajectorySegmentRecord] = []
    if len(dedup_rows) >= 2:
        cur_files = [os.path.basename(dedup_rows[0][2]), os.path.basename(dedup_rows[1][2])]
        cur_t_start = dedup_rows[0][0]
        cur_t_end = dedup_rows[1][0]
        cur_dt = round(cur_t_end - cur_t_start, 4)
        seg_idx = 0
        for i in range(2, len(dedup_rows)):
            dt_i = round(dedup_rows[i][0] - dedup_rows[i - 1][0], 4)
            if abs(dt_i - cur_dt) <= 1e-3:
                cur_files.append(os.path.basename(dedup_rows[i][2]))
                cur_t_end = dedup_rows[i][0]
            else:
                segments.append(
                    TrajectorySegmentRecord(
                        segment_id=f"seg_{seg_idx}_dt{cur_dt:.2f}s",
                        num_frames=len(cur_files),
                        dt_phys_s=cur_dt,
                        t_start_s=cur_t_start,
                        t_end_s=cur_t_end,
                        file_names=tuple(cur_files),
                    )
                )
                seg_idx += 1
                cur_files = [os.path.basename(dedup_rows[i - 1][2]), os.path.basename(dedup_rows[i][2])]
                cur_t_start = dedup_rows[i - 1][0]
                cur_t_end = dedup_rows[i][0]
                cur_dt = dt_i
        segments.append(
            TrajectorySegmentRecord(
                segment_id=f"seg_{seg_idx}_dt{cur_dt:.2f}s",
                num_frames=len(cur_files),
                dt_phys_s=cur_dt,
                t_start_s=cur_t_start,
                t_end_s=cur_t_end,
                file_names=tuple(cur_files),
            )
        )

    # Load up to `max_frames_to_load` from the first longest constant-dt segment to verify transpose & NaN scrubbing
    best_seg = max(segments, key=lambda s: s.num_frames)
    sample_names = best_seg.file_names[: min(max_frames_to_load, len(best_seg.file_names))]
    loaded_frames: list[np.ndarray] = []
    solid_nan_counts: list[int] = []
    fluid_mask_zyx: np.ndarray | None = None

    for fname in sample_names:
        with np.load(dpath / fname, allow_pickle=False) as d:
            u_raw = np.asarray(d["u"], dtype=np.float32)
            v_span_raw = np.asarray(d["v_span"], dtype=np.float32)
            w_cross_raw = np.asarray(d["w_cross"], dtype=np.float32)
            p_raw = np.asarray(d["p"], dtype=np.float32)
            frame_zyx = transpose_yzx_to_zyx_fields(u_raw, w_cross_raw, v_span_raw, p_raw)
            nan_mask_u = ~np.isfinite(frame_zyx[0])
            solid_nan_counts.append(int(nan_mask_u.sum()))
            if fluid_mask_zyx is None:
                if reference_geometry_npz is not None and Path(reference_geometry_npz).exists():
                    with np.load(reference_geometry_npz, allow_pickle=False) as ref_d:
                        fluid_mask_zyx = (1.0 - (np.asarray(ref_d["solid_mask"]) > 0.5).astype(np.float32))
                else:
                    # Solid obstacle cells are simultaneously NaN across all 4 physical channels
                    all_ch_nan = np.all(~np.isfinite(frame_zyx), axis=0)
                    fluid_mask_zyx = (~all_ch_nan).astype(np.float32)
            valid_fluid = fluid_mask_zyx > 0.5
            # Strictly check finiteness inside valid fluid domain BEFORE scrubbing solid NaNs
            if not np.all(np.isfinite(frame_zyx[:, valid_fluid])):
                raise PhysicsContractError(
                    f"shedding snapshot '{fname}' contains NaN/Inf inside the valid fluid domain"
                )
            frame_zyx[:, ~valid_fluid] = 0.0
            loaded_frames.append(frame_zyx)

    assert fluid_mask_zyx is not None
    normalizer = Flow3DNormalizer()
    stacked = np.stack(loaded_frames, axis=0)
    _, b_sample = normalizer.normalize(stacked, fluid_mask_zyx)

    return {
        "format": "c04_shedding_npz_directory",
        "path": str(dpath),
        "total_files": len(files),
        "unique_timestamp_files": len(dedup_rows),
        "duplicate_timestamps": duplicate_timestamps,
        "raw_shape_yzx": [96, 64, 192],
        "standardized_shape_zyx": [64, 96, 192],
        "velocity_channel_mapping": {"X_u": "u", "Y_v": "w_cross", "Z_w": "v_span"},
        "solid_nan_count_per_frame": solid_nan_counts[0] if solid_nan_counts else 0,
        "constant_dt_segments": [
            {
                "segment_id": s.segment_id,
                "num_frames": s.num_frames,
                "dt_phys_s": s.dt_phys_s,
                "t_start_s": s.t_start_s,
                "t_end_s": s.t_end_s,
                "max_rollout_from_L4": max(0, s.num_frames - 4),
            }
            for s in segments
        ],
        "longest_constant_dt_segment": {
            "segment_id": best_seg.segment_id,
            "num_frames": best_seg.num_frames,
            "dt_phys_s": best_seg.dt_phys_s,
            "max_rollout_from_L4": max(0, best_seg.num_frames - 4),
        },
        "sample_b_stats_mean": b_sample.mean(axis=0).tolist(),
    }


def inspect_world_model_dataset_manifest(
    dataset_dir: str | Path,
) -> dict[str, Any]:
    """Inspect `03_world_model_dataset/manifest.json` + Tier-1 & RAM-pool audit and quarantine bad runs."""
    ddir = Path(dataset_dir)
    manifest_path = ddir / "manifest.json"
    if not manifest_path.exists():
        raise FileNotFoundError(f"world model dataset manifest not found: {manifest_path}")
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))

    tier1_path = ddir / "multi_re_tier1_certification_summary.json"
    tier1 = json.loads(tier1_path.read_text(encoding="utf-8")) if tier1_path.exists() else {}
    tier1_by_re: dict[int, dict[str, Any]] = {}
    for case in tier1.get("cases", []):
        if "target_Re" in case:
            tier1_by_re[int(round(float(case["target_Re"])))] = case

    assess_path = ddir / "extraction_and_rampool_assessment.json"
    assess = json.loads(assess_path.read_text(encoding="utf-8")) if assess_path.exists() else {}
    ram_audit = assess.get("ram_pool_audit", {}).get("integrity_checks", {})

    eligible_trajectories: list[dict[str, Any]] = []
    quarantined_trajectories: list[dict[str, Any]] = []

    # 1. Check solvers already quarantined in manifest
    for s_name, s_info in manifest.get("quarantined_solvers", {}).items():
        quarantined_trajectories.append({
            "case_id": s_name,
            "reason": f"solver Re mismatch: nominal={s_info.get('nominal_re_from_name')} vs actual={s_info.get('actual_comsol_re')}",
            "status": "QUARANTINED_SOLVER_MISMATCH",
        })

    # 2. Audit each trajectory entry in manifest
    for traj in manifest.get("trajectories", []):
        cid = str(traj.get("case_id", "unknown"))
        re_val = float(traj.get("reynolds_number", 0.0))
        u0_val = float(traj.get("u0_m_s", 0.0))
        d_val = float(traj.get("cylinder_diameter_m", 0.3))
        nu_val = float(traj.get("kinematic_viscosity_m2_s", 1.1889e-6))
        gt_verified = bool(traj.get("ground_truth_verified", False))
        gt_warning = traj.get("ground_truth_warning")
        num_steps = int(traj.get("num_steps", 0))
        dt_phys = float(traj.get("dt_phys_mean_s", 0.0))
        dt_ctu = float(traj.get("dt_ctu_mean", 0.0))
        channels = list(traj.get("channels", []))

        reasons: list[str] = []
        if not gt_verified:
            reasons.append("ground_truth_verified is False in manifest.json")
        if gt_warning:
            reasons.append(f"ground_truth_warning: {gt_warning}")
        if cid in str(ram_audit.get("slot_2_to_26_provenance", "")):
            reasons.append(f"RAM-pool audit flagged synthetic rank-2 interpolation: {ram_audit.get('slot_2_to_26_provenance')}")

        # Physics consistency check Re ≈ |U0|*D/nu and positive dt_phys / dt_ctu
        if dt_phys <= 0 or not np.isfinite(dt_phys):
            reasons.append(f"invalid non-positive dt_phys_mean_s: {dt_phys}")
        else:
            try:
                Flow3DConditions(
                    reynolds_number=re_val,
                    u0_m_s=u0_val,
                    diameter_m=d_val,
                    viscosity_m2_s=nu_val,
                    dt_phys_s=dt_phys,
                    dt_ctu=dt_ctu if dt_ctu > 0 else None,
                )
            except PhysicsContractError as exc:
                reasons.append(str(exc))

        h5_fname = str(traj.get("file_name", ""))
        h5_path = ddir / h5_fname if h5_fname else None
        h5_exists = bool(h5_path is not None and h5_path.exists())

        t1_case = tier1_by_re.get(int(round(re_val)), {})
        t1_status = str(t1_case.get("status", "UNKNOWN"))

        record = {
            "case_id": cid,
            "file_name": traj.get("file_name"),
            "file_exists_on_disk": h5_exists,
            "reynolds_number": re_val,
            "u0_m_s": u0_val,
            "num_steps": num_steps,
            "max_rollout_from_L4": max(0, num_steps - 4),
            "dt_phys_mean_s": dt_phys,
            "dt_ctu_mean": dt_ctu,
            "raw_h5_channels": channels,
            "requires_ch4_ch5_swap_and_mask_flip": channels[-2:] == ["sdf_star", "solid_mask"],
            "tier1_limit_cycle_status": t1_status,
        }
        if reasons:
            record["quarantine_reasons"] = reasons
            record["status"] = "QUARANTINED"
            quarantined_trajectories.append(record)
        else:
            record["status"] = "ELIGIBLE"
            eligible_trajectories.append(record)

    return {
        "format": "world_model_multi_re_hdf5_manifest",
        "path": str(ddir),
        "eligible_trajectory_count": len(eligible_trajectories),
        "quarantined_count": len(quarantined_trajectories),
        "eligible_trajectories": eligible_trajectories,
        "quarantined_trajectories": quarantined_trajectories,
        "max_supported_rollout_horizon_from_L4": max(
            (t["max_rollout_from_L4"] for t in eligible_trajectories), default=0
        ),
        "h100_rollout_status": "BLOCKED_BY_50_STEP_TRAJECTORY_LENGTH (requires >=104 contiguous steps)",
    }


def load_world_model_h5_trajectory(
    h5_path: str | Path,
    case_id: str = "re_multi_wm",
    ancestor_id: str | None = None,
    reynolds_number: float | None = None,
    u0_m_s: float | None = None,
    diameter_m: float = 0.3,
    viscosity_m2_s: float = 1.1889e-6,
    dt_phys_s: float = 0.02,
    dt_ctu: float | None = None,
    sdf_clip: float | None = 8.0,
    check_rank_degeneracy: bool = True,
    normalize: bool = True,
) -> tuple[Flow3DBatch, dict[str, Any]]:
    """Fork-safe HDF5 trajectory loader for `03_world_model_dataset/*.h5` (`h5py>=3.14`)."""
    try:
        import h5py  # type: ignore[import-untyped]
    except ImportError as exc:
        raise ImportError(
            "load_world_model_h5_trajectory requires h5py>=3.14. Install with `pip install -e \".[data]\"`."
        ) from exc

    p = Path(h5_path)
    if not p.exists():
        raise FileNotFoundError(f"HDF5 trajectory file not found: {p}")

    with h5py.File(p, "r") as f:
        attrs = {k: (v.tolist() if hasattr(v, "tolist") else v) for k, v in f.attrs.items()}
        if bool(attrs.get("ground_truth_verified", True)) is False:
            raise PhysicsContractError(f"quarantined HDF5 file '{p.name}': ground_truth_verified is False")
        tensor_key = None
        for candidate in ("fields", "data", "frames", "tensor"):
            if candidate in f and len(f[candidate].shape) == 5:
                tensor_key = candidate
                break
        if tensor_key is None:
            five_d = [k for k in f.keys() if hasattr(f[k], "shape") and len(f[k].shape) == 5]
            if not five_d:
                raise PhysicsContractError(f"no 5D (T, 6, Z, Y, X) dataset found in {p}; keys={list(f.keys())}")
            tensor_key = five_d[0]
        raw_t6zyx = np.asarray(f[tensor_key][...], dtype=np.float32)

    field_t4zyx, geom_t2zyx = convert_h5_6channel_to_field_and_geometry(raw_t6zyx, sdf_clip=sdf_clip)
    if check_rank_degeneracy:
        is_degen, eff_rank = detect_temporal_rank_degeneracy(field_t4zyx)
        if is_degen:
            raise PhysicsContractError(
                f"quarantined HDF5 trajectory '{p.name}': synthetic rank-{eff_rank} linear interpolation detected"
            )
    else:
        eff_rank = int(field_t4zyx.shape[0])

    geometry_1_2zyx = geom_t2zyx[0:1]
    fluid_mask = geometry_1_2zyx[0, 0]
    if normalize:
        normalizer = Flow3DNormalizer()
        _, b_stats = normalizer.normalize(field_t4zyx[None, ...], fluid_mask)
    else:
        b_stats = None

    re_resolved = reynolds_number if reynolds_number is not None else (
        float(attrs["reynolds_number"]) if "reynolds_number" in attrs else None
    )
    u0_resolved = u0_m_s if u0_m_s is not None else (
        float(attrs["u0_m_s"]) if "u0_m_s" in attrs else None
    )
    cond = Flow3DConditions(
        reynolds_number=re_resolved,
        u0_m_s=u0_resolved,
        diameter_m=diameter_m,
        viscosity_m2_s=viscosity_m2_s,
        dt_phys_s=dt_phys_s,
        dt_ctu=dt_ctu,
        text_prompt=f"3D cylinder wake Re={re_resolved}",
    )
    anc = ancestor_id or f"anc_{case_id}"
    provs = tuple(
        SampleProvenance(
            case_id=case_id,
            geometry_id="cylinder_3d_D0p3m",
            trajectory_id=p.stem,
            ancestor_id=anc,
            segment_id="seg_0",
            time_idx=t_idx,
            time_phys_s=float(t_idx * dt_phys_s),
            time_ctu=float(t_idx * cond.resolved_dt_ctu),
            ground_truth_verified=True,
        )
        for t_idx in range(field_t4zyx.shape[0])
    )
    spacing_star = (0.0625, 0.0625, 0.0625)
    batch = Flow3DBatch(
        field=field_t4zyx[None, ...],
        geometry=geometry_1_2zyx,
        b=b_stats,
        spacing=spacing_star,
        conditions=(cond,),
        provenance=provs,
    )
    return batch, {
        "path": str(p),
        "tensor_key": tensor_key,
        "num_steps": int(field_t4zyx.shape[0]),
        "effective_temporal_rank": eff_rank,
        "spacing_star": list(spacing_star),
    }
